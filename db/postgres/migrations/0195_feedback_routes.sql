-- 0195_feedback_routes.sql — send "Report a problem" mail to named inboxes.
--
-- A platform admin adds a route in the admin console: an org, an optional
-- list of that org's projects, and up to ten email addresses. When someone
-- sends a report, the server still posts it to Discord, and also emails every
-- route that matches (auth-worker services/feedback-routes.ts).
--
-- project_ids is a JSON array of project ids. NULL or '[]' means the whole
-- org. emails is a JSON array of addresses. Both are written only by the
-- admin routes, which check that every project belongs to the org. Nothing
-- reads the table but the feedback route and the admin console, so it gets
-- no RLS policy and is listed in scripts/rls-coverage.test.ts's UNCOVERED map.
--
-- Idempotent and additive.

CREATE TABLE IF NOT EXISTS feedback_routes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      BIGINT  NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    project_ids TEXT,
    emails      TEXT    NOT NULL,
    label       TEXT,
    enabled     BOOLEAN NOT NULL DEFAULT true,
    created_by  BIGINT  NOT NULL,
    created_at  TIMESTAMPTZ DEFAULT now(),
    updated_at  TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_feedback_routes_org ON feedback_routes(org_id);
