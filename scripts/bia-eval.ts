// Offline accuracy eval for BIA forecasting (ghost-text next word + infill).
//
//   pnpm bia:eval                                  # default corpora
//   pnpm bia:eval -- --corpus /path/a.txt,/path/b.txt --positions 1500
//
// Corpora (default dir: $EBIBLE_CORPUS_DIR or ~/Frontier/EBibleBenchmarks/corpus,
// override with --corpus-dir) are eBible vref-aligned text files (one verse per line, blank lines
// for missing verses) from the sibling EBibleBenchmarks checkout. Every 10th
// non-empty verse is held out; the rest trains the index as validated cells.
// Each language runs twice: the whole Bible, and a 2,000-verse "early project"
// slice, since a translation team gets ghost text long before the Bible is done.
//
// Results go to stdout and to docs/forecast/bia-eval-results.{json,md}.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs"
import { homedir } from "node:os"
import { basename, resolve } from "node:path"
import { runForecastEval, splitHeldOut, type EvalReport } from "../src/lib/forecast/bia-eval"

function arg(name: string): string | undefined {
  const at = process.argv.indexOf(`--${name}`)
  return at >= 0 ? process.argv[at + 1] : undefined
}

const CORPUS_DIR = arg("corpus-dir") ?? process.env.EBIBLE_CORPUS_DIR ?? resolve(homedir(), "Frontier/EBibleBenchmarks/corpus")
const DEFAULT_CORPORA = ["eng-engwebp.txt", "tpi-tpi.txt", "npi-npiulb.txt"]
const EARLY_PROJECT_VERSES = 2000


function pct(x: number): string {
  return `${(x * 100).toFixed(1)}%`
}

interface Row {
  corpus: string
  slice: string
  report: EvalReport
}

const corpora = (arg("corpus")?.split(",") ?? DEFAULT_CORPORA).map((p) =>
  p.includes("/") ? p : resolve(CORPUS_DIR, p),
)
const maxPositions = Number(arg("positions") ?? 1500)
const rows: Row[] = []

for (const path of corpora) {
  if (!existsSync(path)) {
    console.error(`missing corpus: ${path}`)
    process.exitCode = 1
    continue
  }
  const lines = readFileSync(path, "utf8").split("\n")
  for (const [slice, limit] of [["full", undefined], [`first ${EARLY_PROJECT_VERSES}`, EARLY_PROJECT_VERSES]] as const) {
    const { train, test } = splitHeldOut(lines, 10, limit)
    // The early-project slice is scored on held-out verses from the same span.
    const heldOut = limit === undefined ? test : test.slice(0, Math.ceil(limit / 9))
    const report = runForecastEval(train, heldOut, { maxPositions })
    rows.push({ corpus: basename(path, ".txt"), slice, report })
    console.log(`\n== ${basename(path)} (${slice}): ${report.trainCells} train / ${report.testCells} test cells, ${report.msPerQuery.toFixed(2)} ms/query`)
    for (const task of ["next", "infill"] as const) {
      for (const [method, acc] of Object.entries(report[task])) {
        console.log(`  ${task.padEnd(6)} ${method.padEnd(48)} top1 ${pct(acc.top1).padStart(6)}  top3 ${pct(acc.top3).padStart(6)}  coverage ${pct(acc.coverage)}`)
      }
    }
  }
}

const outDir = resolve(import.meta.dirname, "../docs/forecast")
mkdirSync(outDir, { recursive: true })
writeFileSync(resolve(outDir, "bia-eval-results.json"), `${JSON.stringify(rows, null, 2)}\n`)

const md: string[] = [
  "# BIA forecasting — offline eval",
  "",
  "Generated by `pnpm bia:eval` (scripts/bia-eval.ts). Every 10th verse held out;",
  `at most ${maxPositions} scored positions per task. Accuracy is exact match of the`,
  "lower-cased token. \"shipped\" is the configuration the editor uses.",
  "",
]
for (const { corpus, slice, report } of rows) {
  md.push(`## ${corpus} — ${slice} (${report.trainCells} train / ${report.testCells} held-out cells, ${report.msPerQuery.toFixed(2)} ms/query)`, "")
  md.push("| task | method | top-1 | top-3 | coverage |", "| --- | --- | ---: | ---: | ---: |")
  for (const task of ["next", "infill"] as const) {
    for (const [method, acc] of Object.entries(report[task])) {
      md.push(`| ${task} | ${method} | ${pct(acc.top1)} | ${pct(acc.top3)} | ${pct(acc.coverage)} |`)
    }
  }
  md.push("")
}
writeFileSync(resolve(outDir, "bia-eval-results.md"), md.join("\n"))
console.log(`\nwrote ${outDir}/bia-eval-results.{json,md}`)
