// AQU-1937: bundle the first-party Door43 importer extension.
//
// The extension's code is src/lib/dcs/extension/door43-importer-main.ts plus
// the SAME Door43 modules the built-in import uses (catalog, manifest,
// resource routes, parsers, deterministic ids). This bundles them into one
// classic script and writes it, with a hash of every input file, to
// shared/tools/first-party/door43-importer.bundle.ts — the reviewed source the
// server installs. door43-bundle.test.ts fails when an input changed and the
// bundle was not rebuilt:  npx tsx scripts/build-door43-extension.ts

import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { build, type Rollup } from "vite"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const ENTRY = path.join(ROOT, "src/lib/dcs/extension/door43-importer-main.ts")
const OUT = path.join(ROOT, "shared/tools/first-party/door43-importer.bundle.ts")

export async function bundleDoor43(): Promise<{ code: string; inputs: string[] }> {
  const result = await build({
    configFile: false,
    logLevel: "silent",
    root: ROOT,
    resolve: { alias: { "@": path.join(ROOT, "src") } },
    define: { "import.meta.env": JSON.stringify({}) },
    build: {
      write: false,
      minify: true,
      lib: { entry: ENTRY, formats: ["iife"], name: "AquillaDoor43Importer", fileName: () => "door43.js" },
      rollupOptions: { output: { inlineDynamicImports: true } },
    },
  })
  const outputs = (Array.isArray(result) ? result : [result]) as Rollup.RollupOutput[]
  const chunk = outputs.flatMap((o) => o.output).find((o): o is Rollup.OutputChunk => o.type === "chunk")
  if (!chunk) throw new Error("no bundle produced")
  const inputs = Object.keys(chunk.modules)
    .filter((m) => m.startsWith(path.join(ROOT, "src")) || m.startsWith(path.join(ROOT, "shared")))
    .map((m) => path.relative(ROOT, m).split(path.sep).join("/"))
    .sort()
  return { code: chunk.code, inputs }
}

/** Hash of the bundle's own input files (the staleness check recomputes it). */
export function hashInputs(inputs: readonly string[]): string {
  const h = createHash("sha256")
  for (const rel of inputs) {
    h.update(rel)
    h.update(readFileSync(path.join(ROOT, rel)))
  }
  return h.digest("hex")
}

async function main(): Promise<void> {
  const { code, inputs } = await bundleDoor43()
  const file = `// GENERATED by scripts/build-door43-extension.ts — do not edit by hand.
// The first-party Door43 importer extension's script (AQU-1937).
/* eslint-disable */
export const DOOR43_IMPORTER_INPUTS: readonly string[] = ${JSON.stringify(inputs, null, 2)}
export const DOOR43_IMPORTER_INPUT_HASH = ${JSON.stringify(hashInputs(inputs))}
export const DOOR43_IMPORTER_SCRIPT = ${JSON.stringify(code)}
`
  writeFileSync(OUT, file)
  console.log(`wrote ${path.relative(ROOT, OUT)} (${code.length} bytes, ${inputs.length} inputs)`)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) void main()
