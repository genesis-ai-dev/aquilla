// ── Sanity checks on constants ─────────────────────────────────────────────────

describe("confidence threshold constants", () => {
  it("exports CONFIDENCE_MIN < CONFIDENCE_AMBER < CONFIDENCE_HIGH", () => {
    expect(CONFIDENCE_MIN).toBeLessThan(CONFIDENCE_AMBER)
    expect(CONFIDENCE_AMBER).toBeLessThan(CONFIDENCE_HIGH)
  })

  it("thresholds are in [0, 1]", () => {
    expect(CONFIDENCE_MIN).toBeGreaterThanOrEqual(0)
    expect(CONFIDENCE_HIGH).toBeLessThanOrEqual(1)
  })
})

// ── Cold-start (Dice) path ───────────────────────────────────────────────────

describe("buildAlignmentModel — cold-start Dice path", () => {
  it("returns a cold model for < 50 pairs", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    expect(model.isWarm).toBe(false)
    expect(model.pairCount).toBe(SMALL_CORPUS.length)
  })

  it("alignCell returns links on a known pair in the corpus", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    const links = alignCell(
      "God created the heavens",
      "Dieu créa les cieux",
      model,
    )
    expect(links.length).toBeGreaterThan(0)
    // "god" ↔ "dieu" should appear as a high-confidence link
    const godLink = links.find((l) => l.srcToken === "god" && l.tgtToken === "dieu")
    expect(godLink).toBeDefined()
    expect(godLink!.confidence).toBeGreaterThan(CONFIDENCE_MIN)
  })

  it("alignCell links have confidence in [0, 1]", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    const links = alignCell(
      "God said let there be light",
      "Dieu dit que la lumière soit",
      model,
    )
    for (const l of links) {
      expect(l.confidence).toBeGreaterThanOrEqual(0)
      expect(l.confidence).toBeLessThanOrEqual(1)
    }
  })

  it("alignCell threshold filter works", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    const allLinks = alignCell(
      "God created the heavens",
      "Dieu créa les cieux",
      model,
      { threshold: 0 },
    )
    const highLinks = alignCell(
      "God created the heavens",
      "Dieu créa les cieux",
      model,
      { threshold: CONFIDENCE_HIGH },
    )
    // High threshold should return fewer (or equal) links
    expect(highLinks.length).toBeLessThanOrEqual(allLinks.length)
    for (const l of highLinks) {
      expect(l.confidence).toBeGreaterThanOrEqual(CONFIDENCE_HIGH)
    }
  })

  it("returns empty array for empty source", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    expect(alignCell("", "Dieu créa", model)).toEqual([])
  })

  it("returns empty array for empty target", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    expect(alignCell("God created", "", model)).toEqual([])
  })

  it("returns empty array for completely unseen tokens (threshold 0.1)", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    // Neither side was in training corpus
    const links = alignCell("xyzzy plugh", "zork frotz", model)
    expect(links).toEqual([])
  })

  it("excludes low-confidence noise below default threshold", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    const links = alignCell(
      "God created",
      "Dieu créa",
      model,
    )
    for (const l of links) {
      expect(l.confidence).toBeGreaterThanOrEqual(CONFIDENCE_MIN)
    }
  })
})

