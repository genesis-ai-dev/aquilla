// ── Online update hooks ───────────────────────────────────────────────────────

describe("confirmAlignment", () => {
  it("increases confidence of confirmed pair", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    const before = alignCell("God created", "Dieu créa", model, { threshold: 0 })
    const godBefore = before.find((l) => l.srcToken === "god" && l.tgtToken === "dieu")
    const confidenceBefore = godBefore?.confidence ?? 0

    confirmAlignment("god", "dieu", model)

    const after = alignCell("God created", "Dieu créa", model, { threshold: 0 })
    const godAfter = after.find((l) => l.srcToken === "god" && l.tgtToken === "dieu")
    const confidenceAfter = godAfter?.confidence ?? 0

    expect(confidenceAfter).toBeGreaterThanOrEqual(confidenceBefore)
  })

  it("is idempotent in that calling it multiple times only increases confidence", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    confirmAlignment("god", "dieu", model)
    const links1 = alignCell("God created", "Dieu créa", model, { threshold: 0 })
    const c1 = links1.find((l) => l.srcToken === "god" && l.tgtToken === "dieu")?.confidence ?? 0

    confirmAlignment("god", "dieu", model)
    const links2 = alignCell("God created", "Dieu créa", model, { threshold: 0 })
    const c2 = links2.find((l) => l.srcToken === "god" && l.tgtToken === "dieu")?.confidence ?? 0

    expect(c2).toBeGreaterThanOrEqual(c1)
  })
})

describe("invalidateAlignment", () => {
  it("decreases or zeroes confidence of invalidated pair", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    const before = alignCell("God created", "Dieu créa", model, { threshold: 0 })
    const godBefore = before.find((l) => l.srcToken === "god" && l.tgtToken === "dieu")
    const confidenceBefore = godBefore?.confidence ?? 0

    // Invalidate many times to push it down
    invalidateAlignment("god", "dieu", model)
    invalidateAlignment("god", "dieu", model)
    invalidateAlignment("god", "dieu", model)

    const after = alignCell("God created", "Dieu créa", model, { threshold: 0 })
    const godAfter = after.find((l) => l.srcToken === "god" && l.tgtToken === "dieu")
    const confidenceAfter = godAfter?.confidence ?? 0

    expect(confidenceAfter).toBeLessThanOrEqual(confidenceBefore)
  })

  it("does not produce negative counts (no crash)", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    // Invalidate far more times than any count could be — should not throw
    for (let i = 0; i < 20; i++) {
      invalidateAlignment("god", "dieu", model)
    }
    expect(() =>
      alignCell("God created", "Dieu créa", model, { threshold: 0 }),
    ).not.toThrow()
  })
})

// ── Seeds ────────────────────────────────────────────────────────────────────

describe("AlignmentSeed integration", () => {
  it("positive seed boosts alignment of seeded pair", () => {
    const modelWithout = buildAlignmentModel(SMALL_CORPUS)
    const seeds: AlignmentSeed[] = [{ srcToken: "earth", tgtToken: "terre", weight: 10 }]
    const modelWith = buildAlignmentModel(SMALL_CORPUS, seeds)

    const linksWithout = alignCell(
      "the earth was good",
      "la terre était bonne",
      modelWithout,
      { threshold: 0 },
    )
    const linksWith = alignCell(
      "the earth was good",
      "la terre était bonne",
      modelWith,
      { threshold: 0 },
    )

    const cWithout = linksWithout.find(
      (l) => l.srcToken === "earth" && l.tgtToken === "terre",
    )?.confidence ?? 0
    const cWith = linksWith.find(
      (l) => l.srcToken === "earth" && l.tgtToken === "terre",
    )?.confidence ?? 0

    expect(cWith).toBeGreaterThanOrEqual(cWithout)
  })

  it("negative seed penalizes alignment", () => {
    const modelWithout = buildAlignmentModel(SMALL_CORPUS)
    const seeds: AlignmentSeed[] = [{ srcToken: "god", tgtToken: "dieu", weight: -5 }]
    const modelWith = buildAlignmentModel(SMALL_CORPUS, seeds)

    const linksWithout = alignCell("God said", "Dieu dit", modelWithout, { threshold: 0 })
    const linksWithSeeds = alignCell("God said", "Dieu dit", modelWith, { threshold: 0 })

    const cWithout = linksWithout.find((l) => l.srcToken === "god" && l.tgtToken === "dieu")?.confidence ?? 0
    const cWith = linksWithSeeds.find((l) => l.srcToken === "god" && l.tgtToken === "dieu")?.confidence ?? 0
    expect(cWith).toBeLessThanOrEqual(cWithout)
  })
})

// ── Link structure ────────────────────────────────────────────────────────────

describe("AlignmentLink structure", () => {
  it("links have all required fields", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    const links = alignCell("God created", "Dieu créa", model)
    for (const l of links) {
      expect(typeof l.srcIndex).toBe("number")
      expect(typeof l.srcToken).toBe("string")
      expect(typeof l.tgtIndex).toBe("number")
      expect(typeof l.tgtToken).toBe("string")
      expect(typeof l.confidence).toBe("number")
    }
  })

  it("links are sorted by srcIndex", () => {
    const model = buildAlignmentModel(SMALL_CORPUS)
    const links = alignCell(
      "In the beginning God created the heavens",
      "Au commencement Dieu créa les cieux",
      model,
    )
    for (let i = 1; i < links.length; i++) {
      expect(links[i].srcIndex).toBeGreaterThanOrEqual(links[i - 1].srcIndex)
    }
  })

  it("srcIndex and tgtIndex are within token array bounds", () => {
    const source = "God said let there be light"
    const target = "Dieu dit que la lumière soit"
    const srcLen = source.split(/\s+/).filter(Boolean).length
    const tgtLen = target.split(/\s+/).filter(Boolean).length

    const model = buildAlignmentModel(SMALL_CORPUS)
    const links = alignCell(source, target, model)
    for (const l of links) {
      expect(l.srcIndex).toBeGreaterThanOrEqual(0)
      expect(l.srcIndex).toBeLessThan(srcLen)
      expect(l.tgtIndex).toBeGreaterThanOrEqual(0)
      expect(l.tgtIndex).toBeLessThan(tgtLen)
    }
  })
})

// ── Empty / edge cases ────────────────────────────────────────────────────────

describe("edge cases", () => {
  it("buildAlignmentModel with empty pairs is safe", () => {
    const model = buildAlignmentModel([])
    expect(model.pairCount).toBe(0)
    expect(model.isWarm).toBe(false)
    expect(alignCell("hello", "bonjour", model)).toEqual([])
  })

  it("buildAlignmentModel with single pair is safe", () => {
    const model = buildAlignmentModel([{ source: "God", target: "Dieu" }])
    const links = alignCell("God", "Dieu", model, { threshold: 0 })
    expect(links.length).toBeGreaterThan(0)
  })

  it("seeds on an empty corpus produce links", () => {
    const seeds: AlignmentSeed[] = [
      { srcToken: "God", tgtToken: "Dieu", weight: 10 },
    ]
    const model = buildAlignmentModel([], seeds)
    const links = alignCell("God", "Dieu", model, { threshold: 0 })
    expect(links.length).toBeGreaterThan(0)
    expect(links[0].srcToken).toBe("god")
    expect(links[0].tgtToken).toBe("dieu")
  })
})
